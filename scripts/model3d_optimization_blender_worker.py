"""Trusted fixed Blender 4.5 worker for planar, delimiter-aware decimation.

Never import this module outside Blender. Jobs are generated by the adapter;
no source-supplied Python or arbitrary operation names are executed.
"""
import json
import math
from pathlib import Path
import sys
import bpy
import bmesh
from mathutils import Vector


def canonical(v):return [float(v.x),float(v.z),float(-v.y)]


def main():
    job=json.loads(Path(sys.argv[sys.argv.index('--')+1]).read_text())
    if bpy.app.version[:2]!=(4,5):raise ValueError('Blender 4.5 LTS is required')
    if job['mode']=='create':
        bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
        bpy.ops.import_scene.gltf(filepath=job['input'],merge_vertices=False,import_pack_images=True)
        objects={o.name:o for o in bpy.data.objects if o.type=='MESH'}
        if set(objects)!=set(job['parts']):raise ValueError('Imported part names changed')
        for name,part in job['parts'].items():
            obj=objects[name];mesh=obj.data
            # Mark all edges touching explicit feature coordinates as sharp;
            # DISSOLVE's SHARP delimiter retains those edges in this profile.
            points=[Vector((p[0],-p[2],p[1])) for p in part['protected']]
            matches=[{v.index for v in mesh.vertices if (obj.matrix_world@v.co-p).length<=job['point_tolerance']} for p in points]
            if any(not match for match in matches):raise ValueError('Source feature coordinates did not match imported vertices')
            protected=set().union(*matches) if matches else set()
            bm=bmesh.new()
            try:
                bm.from_mesh(mesh);bm.verts.ensure_lookup_table();bm.verts.index_update()
                # Excluding vertices and every incident edge is essential:
                # Decimate's SHARP delimiter alone can dissolve degree-2 points.
                eligible_vertices=[v for v in bm.verts if v.index not in protected]
                eligible_edges=[e for e in bm.edges if all(v.index not in protected for v in e.verts)]
                bmesh.ops.dissolve_limit(bm,angle_limit=math.radians(job['angle_degrees']),
                    use_dissolve_boundaries=False,verts=eligible_vertices,edges=eligible_edges,
                    delimit={'NORMAL','MATERIAL','SEAM','SHARP','UV'})
                bmesh.ops.triangulate(bm,faces=list(bm.faces),quad_method='BEAUTY',ngon_method='EAR_CLIP')
                for face in bm.faces:face.smooth=False
                bm.to_mesh(mesh);mesh.update()
                if mesh.has_custom_normals:
                    mesh.normals_split_custom_set_from_vertices([(0.,0.,0.)]*len(mesh.vertices))
            finally:bm.free()
        bpy.ops.wm.save_as_mainfile(filepath=job['blend'],compress=True)
    elif job['mode']=='reopen':
        bpy.ops.wm.open_mainfile(filepath=job['blend'],load_ui=False,use_scripts=False)
        if bpy.data.libraries:raise ValueError('Linked libraries are not allowed')
        if any(i.source=='FILE' and not i.packed_file for i in bpy.data.images):raise ValueError('Unpacked images are not allowed')
        bpy.ops.export_scene.gltf(filepath=job['output'],export_format='GLB',export_yup=True,
            export_animations=False,export_skins=False,export_morph=False,export_extras=True)
    else:raise ValueError('Unsupported trusted operation')
    meshes=[o for o in bpy.data.objects if o.type=='MESH']
    report=dict(blender_version=bpy.app.version_string,mode=job['mode'],
        meshes=[dict(name=o.name,vertices=len(o.data.vertices),polygons=len(o.data.polygons),
                     uv_layers=len(o.data.uv_layers),materials=[m.name for m in o.data.materials],
                     packed_images=sum(bool(i.packed_file) for i in bpy.data.images)) for o in meshes])
    Path(job['report']).write_text(json.dumps(report,indent=2))


if __name__=='__main__':main()

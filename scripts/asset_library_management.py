"""Trusted managed adapters for canonical version, replacement and index repair.

Staging is an isolated canonical library. Publication uses the native library's
CAS transaction; receipts never substitute for checking actual canonical state.
"""
from __future__ import annotations
from copy import deepcopy
import hashlib
from pathlib import Path

from asset_library import AssetLibrary, read_source_bytes
from asset_library_contracts import validate
from asset_library_versions import AssetVersions
from asset_library_dependencies import DependencyGraph, apply_replacement
from rig_errors import RigError, atomic_bytes, object_hash


def fail(code,message):
    raise RigError('LIBRARY_MANAGEMENT_'+code,message,stage='asset-management')


def ref(manifest):
    return dict(id=manifest['identity']['id'],version=manifest['version'],sha256=manifest['manifest_sha256'])


class StageLibrary(AssetLibrary):
    """Native staging registration may safely reuse its *identical* version."""
    def register(self,manifest,sources,**options):
        try:return super().register(manifest,sources,**options)
        except RigError as exc:
            if exc.report['code']!='LIBRARY_IMMUTABLE':raise
            existing=self.resolve(ref(manifest))
            if existing!=manifest:fail('CONFLICT','Existing staged version differs.')
            return ref(manifest)


class ManagementAdapter:
    def __init__(self,owner,operation,parameters):
        self.owner=owner;self.operation=operation;self.parameters=deepcopy(parameters)

    def admit(self, *, replay=False):
        from asset_library_operations import _path,request
        p=request(self.parameters)
        if self.operation=='version':
            action=p.get('action')
            schemas={'create':({'action','manifest','sources'},{'previous'}),
                'promote':({'action','reference','expected_revision'},{'reason','consumers'}),
                'rollback':({'action','asset_id','expected_revision'},{'reason','consumers'})}
            if action not in schemas:fail('REQUEST','Choose create, promote or rollback version action.')
            required,optional=schemas[action]
        elif self.operation=='replace':required,optional={'plan','versions'},set()
        elif self.operation=='repair':required,optional={'source','digest','expected_bytes'},set()
        else:fail('REQUEST','Unknown managed management operation.')
        internal={'input_hashes','baseline','lifecycle'}
        if not replay and set(p)&internal:fail('REQUEST','Admission metadata is generated by the managed authority, not caller input.')
        if not required<=p.keys() or set(p)-required-optional-internal:fail('REQUEST','Missing or unknown management request fields.')
        baseline=self.owner.library.list_references()
        # Preserve supplied admission baseline on retries; unrelated additions are
        # allowed, while per-identity publication CAS remains bound below.
        p.setdefault('baseline',baseline)
        if not isinstance(p['baseline'],list) or len(p['baseline'])>4096:fail('LIMIT','Invalid baseline reference inventory.')
        for reference in p['baseline']:validate(reference,'AssetRef')
        hashes={}
        if self.operation=='version' and action=='create':
            validate(p['manifest'],'AssetVersion')
            if not isinstance(p['sources'],dict) or set(p['sources'])!={f['path'] for f in p['manifest']['files']}:fail('REQUEST','Version sources must exactly match its manifest.')
            for name,value in p['sources'].items():
                path=_path(value,exists=True);data=read_source_bytes(path)
                p['sources'][name]=str(path);hashes[name]=hashlib.sha256(data).hexdigest()
        if self.operation=='repair':
            path=_path(p['source'],exists=True);data=read_source_bytes(path)
            if type(p['expected_bytes']) is not int or len(data)!=p['expected_bytes'] or hashlib.sha256(data).hexdigest()!=p['digest']:fail('HASH','Repair source must match the exact expected digest and size.')
            if 'input_hashes' not in p:
                with self.owner.library._connect() as db:row=db.execute('SELECT payload FROM blobs WHERE sha256=?',(p['digest'],)).fetchone()
                if row and row[0]==data:fail('CONFLICT','Repair target is already intact.')
            p['source']=str(path);hashes=dict(source=p['digest'])
        if p.get('input_hashes',hashes)!=hashes:fail('STALE','Source bytes changed since admission; submit a new job.')
        p['input_hashes']=hashes
        if self.operation=='version' and action in ('promote','rollback'):
            asset_id=p['reference']['id'] if action=='promote' else p['asset_id']
            versions=AssetVersions(self.owner.library);state=versions.state(asset_id)
            if type(p['expected_revision']) is not int or p['expected_revision']<0:fail('CAS','Expected lifecycle revision must be a nonnegative integer.')
            p.setdefault('lifecycle',dict(asset_id=asset_id,stream=versions._stream(asset_id),expected_revision=p['expected_revision']))
            if p['lifecycle']!=dict(asset_id=asset_id,stream=versions._stream(asset_id),expected_revision=p['expected_revision']):fail('REQUEST','Lifecycle admission record differs.')
            if state['revision']!=p['expected_revision']:fail('CAS','Lifecycle changed before staging; reload explicit revision.')
        self.parameters=deepcopy(p)
        return p

    def _library(self,context):
        path=context.stage_dir/'management-library'
        return StageLibrary(path,create=not path.exists())

    @staticmethod
    def _write_payloads(context,library,manifest):
        paths={}
        for file in manifest['files']:
            context.check_cancelled();path=context.stage_dir/'management-payloads'/file['sha256']
            path.parent.mkdir(exist_ok=True)
            if not path.exists():atomic_bytes(path,library.read_own_file(ref(manifest),file['path']))
            paths[file['path']]=path
        return paths

    def _clone(self,context,p):
        library=self._library(context)
        pending={r['sha256']:r for r in p['baseline']}
        while pending:
            advanced=False
            for digest,reference in list(pending.items()):
                manifest=self.owner.library.inspect(reference)
                targets=[d['target'] for d in manifest['dependencies']]+manifest['provenance']['parents']+manifest['metadata']['style_refs']
                if any(t['sha256'] in pending for t in targets):continue
                paths=self._write_payloads(context,self.owner.library,manifest)
                library.register(manifest,paths);pending.pop(digest);advanced=True
            if not advanced:fail('DEPENDENCY','Baseline cannot be cloned in dependency order.')
        return library

    def stage(self,context):
        p=self.admit(replay=True);context.check_cancelled()
        if self.operation=='repair':
            path=context.stage_dir/'repair-payload';atomic_bytes(path,read_source_bytes(p['source']))
            return dict(digest=p['digest'],bytes=p['expected_bytes'])
        library=self._clone(context,p);before={r['sha256'] for r in p['baseline']}
        if self.operation=='replace':
            result=apply_replacement(DependencyGraph({'local':library}),p['plan'],versions=p['versions'])
        else:
            versions=AssetVersions(library);action=p['action']
            if action=='create':
                sources={}
                for name,value in p['sources'].items():
                    payload=read_source_bytes(value)
                    if hashlib.sha256(payload).hexdigest()!=p['input_hashes'][name]:fail('STALE','Version source changed during staging.')
                    target=context.stage_dir/'version-sources'/name;target.parent.mkdir(parents=True,exist_ok=True);atomic_bytes(target,payload);sources[name]=target
                result=versions.create(p['manifest'],sources,previous=p.get('previous'))
            else:
                stream=p['lifecycle']['stream']
                staged_events=library.events(stream)
                for event in self.owner.library.events(stream):
                    if event['revision']<=len(staged_events):
                        if staged_events[event['revision']-1]!=event:fail('CAS','Staged lifecycle prefix differs.')
                    else:library.append_event(stream,expected_revision=event['revision']-1,document=event['document'])
                staged_events=library.events(stream)
                if len(staged_events)>p['expected_revision']:
                    event=staged_events[p['expected_revision']]
                    if '[managed-job:'+context.token+']' not in event['document']['reason']:fail('CAS','Another staged operation owns the lifecycle revision.')
                    return dict(kind='event',stream=stream,event=event)
                arguments={k:v for k,v in p.items() if k in ('reference','asset_id','expected_revision','consumers','reason')}
                arguments['reason']=str(p.get('reason','Managed version selection'))+' [managed-job:'+context.token+']'
                result=getattr(versions,action)(**arguments)
                return dict(kind='event',stream=stream,event=result)
        added=[r for r in library.list_references() if r['sha256'] not in before]
        for reference in added:self._write_payloads(context,library,library.resolve(reference))
        return dict(kind='versions',references=added,result=result)

    def verify(self,context,staged):
        context.check_cancelled()
        if self.operation=='repair':
            payload=read_source_bytes(context.stage_dir/'repair-payload')
            if len(payload)!=staged['bytes'] or hashlib.sha256(payload).hexdigest()!=staged['digest']:fail('HASH','Staged repair bytes differ.')
            return deepcopy(staged)
        if staged['kind']=='event':
            if self._library(context).events(staged['stream'])[-1]!=staged['event']:fail('VERIFY','Staged lifecycle event differs.')
            return deepcopy(staged)
        library=self._library(context)
        for reference in staged['references']:library.resolve(reference)
        return deepcopy(staged)

    def _event_probe(self,verified):
        event=verified['event'];events=self.owner.library.events(verified['stream'])
        matches=[e for e in events if e['revision']==event['revision']]
        if matches:
            if matches[0]!=event:fail('CAS','Another lifecycle event owns the expected revision; preserved.')
            return dict(status='published',receipt=dict(event=event))
        if len(events)!=event['revision']-1:fail('CAS','Lifecycle revision is inconsistent.')
        return dict(status='unpublished')

    def _repair_probe(self,verified):
        # Exact row checking is the canonical index authority; this is read-only
        # because corrupted index data must not block its own repair workflow.
        with self.owner.library._connect() as db:
            row=db.execute('SELECT payload FROM blobs WHERE sha256=?',(verified['digest'],)).fetchone()
        if row and len(row[0])==verified['bytes'] and hashlib.sha256(row[0]).hexdigest()==verified['digest']:
            return dict(status='published',receipt=dict(sha256=verified['digest'],bytes=verified['bytes'],repaired=True))
        return dict(status='unpublished')

    def recover(self,context,staged,verified):
        if self.operation=='repair':return self._repair_probe(verified)
        if verified['kind']=='event':return self._event_probe(verified)
        present=[]
        known={(r['id'],r['version']):r for r in self.owner.library.list_references()}
        for reference in verified['references']:
            candidate=known.get((reference['id'],reference['version']))
            if candidate is not None:
                if candidate!=reference:fail('CONFLICT','A different immutable version owns the publication target.')
                self.owner.library.resolve(reference);present.append(reference)
        if len(present)==len(verified['references']):return dict(status='published',receipt=dict(references=present,result=staged['result']))
        return dict(status='unpublished')

    def publish(self,context,staged,verified):
        context.check_cancelled()
        if self.operation=='repair':
            try:return self.owner.library.recover_blob(verified['digest'],read_source_bytes(context.stage_dir/'repair-payload'),expected_bytes=verified['bytes'])
            except RigError as exc:
                if exc.report['code']!='LIBRARY_CONFLICT':raise
                probe=self._repair_probe(verified)
                if probe['status']!='published':raise
                return probe['receipt']
        if verified['kind']=='event':
            probe=self._event_probe(verified)
            if probe['status']=='published':return probe['receipt']
            event=verified['event']
            result=self.owner.library.append_event(verified['stream'],expected_revision=event['revision']-1,document=event['document'])
            return dict(event=result)
        library=self._library(context);pending=list(verified['references']);published=[]
        while pending:
            advanced=False
            for reference in list(pending):
                manifest=library.resolve(reference)
                targets=[d['target'] for d in manifest['dependencies']]+manifest['provenance']['parents']+manifest['metadata']['style_refs']
                if any(t in pending for t in targets):continue
                current=self.owner.library.list_references();same=[r for r in current if (r['id'],r['version'])==(reference['id'],reference['version'])]
                if same:
                    if same!=[reference]:fail('CONFLICT','Immutable publication target differs.')
                    self.owner.library.resolve(reference)
                else:
                    baseline=[r for r in self.parameters['baseline'] if r['id']==reference['id']]
                    prior=[r for r in published if r['id']==reference['id']]
                    sources={f['path']:context.stage_dir/'management-payloads'/f['sha256'] for f in manifest['files']}
                    self.owner.library.register(manifest,sources,expected_identity_refs=baseline+prior)
                published.append(reference);pending.remove(reference);advanced=True
            if not advanced:fail('DEPENDENCY','Prepared versions cannot be published in dependency order.')
        return dict(references=published,result=staged['result'])


def management_adapter(owner,operation,parameters):
    return ManagementAdapter(owner,operation,parameters)
